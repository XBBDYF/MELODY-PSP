"""Build the built-in IME dictionaries from tools/ime/*.txt.

Outputs src/ime_dict_data.h (compiled into the PRX, no runtime file I/O).

    word|pinyin|freq     pinyin: lowercase concatenated, no tones, no separators
    word|reading|freq    reading: hiragana (ー and ・ allowed)

The files stay small on purpose: a few hundred high-frequency entries are enough
to make search usable, and the header documents how to grow them (see
docs/IME.md). Entries are sorted by key so the runtime can binary-search the
prefix range.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "ime"
OUT = ROOT / "src" / "ime_dict_data.h"

# 字库覆盖检查：只保留每个字都能在点阵字库里找到的词条（可选）
FONT_FILES = ["font12.bin", "font16.bin", "font22.bin", "font32.bin"]


def load_font_codepoints(path):
    import struct
    b = path.read_bytes()
    magic, ver, count, rec, off = struct.unpack_from("<5I", b, 0)
    assert magic == 0x46505350, f"{path}: bad magic"
    return {struct.unpack_from("<I", b, off + i * rec)[0] for i in range(count)}


def parse(path, key_lower):
    rows = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 3:
            sys.exit(f"{path.name}:{n}: expected word|key|freq")
        word, key, freq = parts[0].strip(), parts[1].strip(), parts[2].strip()
        if key_lower:
            key = key.lower()
        if not word or not key:
            sys.exit(f"{path.name}:{n}: empty word/key")
        if not freq.isdigit() or not 1 <= int(freq) <= 9:
            sys.exit(f"{path.name}:{n}: freq must be 1..9")
        if any(ch.isspace() for ch in key):
            sys.exit(f"{path.name}:{n}: key must not contain spaces")
        rows.append((key, word, int(freq)))
    rows.sort(key=lambda r: (r[0], -r[2], r[1]))
    return rows


def emit(rows, name, out):
    out.write(f"static const ImeEntry {name}[] = {{\n")
    for key, word, freq in rows:
        out.write('    {"%s", "%s", %d},\n' % (key, word, freq))
    out.write("};\n")
    out.write(f"static const int {name}_count = (int)(sizeof({name}) / sizeof({name}[0]));\n\n")


def main():
    py = parse(SRC / "pinyin.txt", True)
    ja = parse(SRC / "japanese.txt", False)

    # 只保留字库能画的词条（缺字会在界面上变成方块）
    missing = {}
    for size in ("font12.bin", "font16.bin", "font22.bin", "font32.bin"):
        p = ROOT / "src" / size
        if p.exists():
            missing[size] = load_font_codepoints(p)
    kept_py, kept_ja = [], []
    for rows, kept in ((py, kept_py), (ja, kept_ja)):
        for key, word, freq in rows:
            drop = [ch for ch in word if ord(ch) > 0x7F and
                    all(ord(ch) not in cps for sz, cps in missing.items() if sz in ("font12.bin", "font16.bin"))]
            if drop:
                print(f"drop {word}: font12/16 缺 {''.join(drop)}", file=sys.stderr)
                continue
            kept.append((key, word, freq))

    body = []
    body.append("/* Generated by tools/build_ime_dict.py — do not edit by hand. */\n")
    body.append("/* Sources: tools/ime/pinyin.txt (word|pinyin|freq), tools/ime/japanese.txt (word|reading|freq) */\n\n")
    body.append("#ifndef MELODY_IME_DICT_DATA_H\n#define MELODY_IME_DICT_DATA_H\n\n")
    body.append("#include \"ime_dict.h\"\n\n")

    class Buf:
        def __init__(self):
            self.parts = []

        def write(self, s):
            self.parts.append(s)

        def getvalue(self):
            return "".join(self.parts)

    b = Buf()
    emit(kept_py, "k_ime_pinyin", b)
    emit(kept_ja, "k_ime_kana", b)
    body.append(b.getvalue())
    body.append("#endif\n")
    OUT.write_text("".join(body), encoding="utf-8")

    print(f"pinyin: {len(kept_py)} entries, japanese: {len(kept_ja)} entries")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
